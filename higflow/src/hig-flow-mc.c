// Tabela de dispersao simples sobre o par ordenado de vertices, para contar
// quantos triangulos usam cada aresta.  Sem ela, contar arestas seria O(F^2).
typedef struct { int a, b, n; } _ar;

static int _conta_arestas(const mc_malha *m, int *n_arestas, int *orfas) {
    size_t nb = 1; while (nb < (size_t)(12*m->nt + 16)) nb <<= 1;
    _ar *t = (_ar*) calloc(nb, sizeof(_ar));
    if (!t) return 1;
    for (size_t q = 0; q < nb; q++) t[q].a = -1;
    int na = 0;
    for (int q = 0; q < m->nt; q++) {
        for (int r = 0; r < 3; r++) {
            int a = m->t[3*q+r], b = m->t[3*q+(r+1)%3];
            if (a > b) { int s = a; a = b; b = s; }
            size_t hh = ((size_t)a*73856093u ^ (size_t)b*19349663u) & (nb-1);
            while (t[hh].a >= 0 && !(t[hh].a == a && t[hh].b == b))
                hh = (hh+1) & (nb-1);
            if (t[hh].a < 0) { t[hh].a = a; t[hh].b = b; t[hh].n = 0; na++; }
            t[hh].n++;
        }
    }
    int orf = 0;
    for (size_t q = 0; q < nb; q++) if (t[q].a >= 0 && t[q].n != 2) orf++;
    free(t);
    if (n_arestas) *n_arestas = na;
    if (orfas)     *orfas     = orf;
    return 0;
}

int mc_arestas_orfas(const mc_malha *m) {
    int orf = -1;
    if (_conta_arestas(m, NULL, &orf)) return -1;
    return orf;
}

int mc_euler(const mc_malha *m) {
    int na = 0;
    if (_conta_arestas(m, &na, NULL)) return -1000000;
    return m->nv - na + m->nt;
}

double mc_volume(const mc_malha *m) {
    // Teorema da divergencia: V = (1/6) sum  a . (b x c)
    double V = 0.0;
    for (int q = 0; q < m->nt; q++) {
        const double *a = &m->v[3*m->t[3*q+0]];
        const double *b = &m->v[3*m->t[3*q+1]];
        const double *c = &m->v[3*m->t[3*q+2]];
        V += a[0]*(b[1]*c[2]-b[2]*c[1])
           + a[1]*(b[2]*c[0]-b[0]*c[2])
           + a[2]*(b[0]*c[1]-b[1]*c[0]);
    }
    return V/6.0;
}

double mc_area(const mc_malha *m) {
    double A = 0.0;
    for (int q = 0; q < m->nt; q++) {
        const double *a = &m->v[3*m->t[3*q+0]];
        const double *b = &m->v[3*m->t[3*q+1]];
        const double *c = &m->v[3*m->t[3*q+2]];
        double u[3], w[3], n[3];
        for (int d = 0; d < 3; d++) { u[d] = b[d]-a[d]; w[d] = c[d]-a[d]; }
        n[0] = u[1]*w[2]-u[2]*w[1];
        n[1] = u[2]*w[0]-u[0]*w[2];
        n[2] = u[0]*w[1]-u[1]*w[0];
        A += 0.5*sqrt(n[0]*n[0]+n[1]*n[1]+n[2]*n[2]);
    }
    return A;
}

