void mc_malha_zera(mc_malha *m) { memset(m, 0, sizeof(*m)); }

void mc_malha_libera(mc_malha *m) {
    free(m->v); free(m->t); free(m->vn); memset(m, 0, sizeof(*m));
}

static int _cresce_v(mc_malha *m) {
    if (m->nv < m->cv) return 0;
    int nc = m->cv ? 2*m->cv : 4096;
    double *nv = (double*) realloc(m->v,  3*(size_t)nc*sizeof(double));
    if (!nv) return 1;
    m->v = nv;
    double *nn = (double*) realloc(m->vn, 3*(size_t)nc*sizeof(double));
    if (!nn) return 1;
    m->vn = nn;
    m->cv = nc; return 0;
}
static int _cresce_t(mc_malha *m) {
    if (m->nt < m->ct) return 0;
    int nc = m->ct ? 2*m->ct : 4096;
    int *nt = (int*) realloc(m->t, 3*(size_t)nc*sizeof(int));
    if (!nt) return 1;
    m->t = nt; m->ct = nc;
    return 0;
}

// ------------------------------------------------------------------------
// Extracao
//
// Memoria: duas fatias de valores e os mapas aresta->vertice de duas fatias.
// O(ni*nj), nao O(ni*nj*nk) -- a malha fina de um caso adaptativo nao cabe
// comoda em memoria se guardarmos tudo.
// ------------------------------------------------------------------------

// Estado do laco, para a rotina de solda nao receber quinze argumentos.
typedef struct {
    int ni, nj, k;
    const double *x0, *h;
    double iso;
    const double *vlo, *vhi;      // valores nas fatias k e k+1
    int *exlo, *exhi, *eylo, *eyhi, *ez;
    mc_malha *m;
} _ctx;

// Devolve o indice do vertice da aresta 'e' do cubo (i,j,k), criando-o se
// for a primeira vez.  E' a SOLDA: duas chamadas com a mesma aresta de rede
// devolvem o mesmo indice, venham de cubos diferentes ou nao.  Sem isto a
// superficie sairia com vertices repetidos e, pior, com costura visivel.
static int _vert(_ctx *c, int i, int j, int e) {
    int *mapa; int idx; double pa[3], pb[3], va, vb;
    const int ni = c->ni;
    const double *h = c->h, *x0 = c->x0;
    int ii = i, jj = j, tipo, alto = 0;

    switch (e) {
        case  0: tipo=0; ii=i;   jj=j;   alto=0; break;
        case  2: tipo=0; ii=i;   jj=j+1; alto=0; break;
        case  4: tipo=0; ii=i;   jj=j;   alto=1; break;
        case  6: tipo=0; ii=i;   jj=j+1; alto=1; break;
        case  3: tipo=1; ii=i;   jj=j;   alto=0; break;
        case  1: tipo=1; ii=i+1; jj=j;   alto=0; break;
        case  7: tipo=1; ii=i;   jj=j;   alto=1; break;
        case  5: tipo=1; ii=i+1; jj=j;   alto=1; break;
        case  8: tipo=2; ii=i;   jj=j;   break;
        case  9: tipo=2; ii=i+1; jj=j;   break;
        case 10: tipo=2; ii=i+1; jj=j+1; break;
        case 11: tipo=2; ii=i;   jj=j+1; break;
        default: return -1;
    }
    if      (tipo == 0) mapa = alto ? c->exhi : c->exlo;
    else if (tipo == 1) mapa = alto ? c->eyhi : c->eylo;
    else                mapa = c->ez;

    const int cel = jj*ni + ii;
    if (mapa[cel] >= 0) return mapa[cel];

    const double *vp = (tipo == 2) ? c->vlo : (alto ? c->vhi : c->vlo);
    const int    kp  = (tipo == 2) ? c->k   : (alto ? c->k+1 : c->k);

    if (tipo == 0) {                                  // aresta em x
        va = vp[cel]; vb = vp[cel+1];
        pa[0]=x0[0]+ii*h[0];     pa[1]=x0[1]+jj*h[1]; pa[2]=x0[2]+kp*h[2];
        pb[0]=x0[0]+(ii+1)*h[0]; pb[1]=pa[1];         pb[2]=pa[2];
    } else if (tipo == 1) {                           // aresta em y
        va = vp[cel]; vb = vp[cel+ni];
        pa[0]=x0[0]+ii*h[0]; pa[1]=x0[1]+jj*h[1];     pa[2]=x0[2]+kp*h[2];
        pb[0]=pa[0];         pb[1]=x0[1]+(jj+1)*h[1]; pb[2]=pa[2];
    } else {                                          // aresta em z
        va = c->vlo[cel]; vb = c->vhi[cel];
        pa[0]=x0[0]+ii*h[0]; pa[1]=x0[1]+jj*h[1]; pa[2]=x0[2]+kp*h[2];
        pb[0]=pa[0];         pb[1]=pa[1];         pb[2]=x0[2]+(kp+1)*h[2];
    }

    // Interpolacao linear ate' o cruzamento.  Se os dois valores forem
    // iguais a aresta nao estaria cortada; o 0.5 e' so' para nao dividir
    // por zero se chegar aqui por ruido de ponto flutuante.
    double t = (vb != va) ? (c->iso - va) / (vb - va) : 0.5;
    if (t < 0.0) t = 0.0; else if (t > 1.0) t = 1.0;

    if (_cresce_v(c->m)) return -1;
    idx = c->m->nv;
    for (int d = 0; d < 3; d++) c->m->v[3*idx+d] = pa[d] + t*(pb[d]-pa[d]);
    c->m->vn[3*idx+0] = c->m->vn[3*idx+1] = c->m->vn[3*idx+2] = 0.0;
    c->m->nv++;
    mapa[cel] = idx;
    return idx;
}

int mc_extrai(int ni, int nj, int nk,
              const double x0[3], const double h[3],
              double iso, mc_amostra f, void *ctx, mc_malha *m) {
    if (ni < 2 || nj < 2 || nk < 2) return 0;      // nao ha' cubo
    const size_t np = (size_t)ni*nj;
    double *vlo = (double*) malloc(np*sizeof(double));
    double *vhi = (double*) malloc(np*sizeof(double));
    int *exlo = (int*) malloc(np*sizeof(int)), *exhi = (int*) malloc(np*sizeof(int));
    int *eylo = (int*) malloc(np*sizeof(int)), *eyhi = (int*) malloc(np*sizeof(int));
    int *ez   = (int*) malloc(np*sizeof(int));
    if (!vlo||!vhi||!exlo||!exhi||!eylo||!eyhi||!ez) {
        free(vlo);free(vhi);free(exlo);free(exhi);free(eylo);free(eyhi);free(ez);
        return 1;
    }
    int err = 0;

    for (int j = 0; j < nj; j++) for (int i = 0; i < ni; i++)
        vlo[j*ni+i] = f(i, j, 0, ctx);
    for (size_t q = 0; q < np; q++) { exlo[q] = -1; eylo[q] = -1; }

    for (int k = 0; k < nk-1 && !err; k++) {
        for (int j = 0; j < nj; j++) for (int i = 0; i < ni; i++)
            vhi[j*ni+i] = f(i, j, k+1, ctx);
        for (size_t q = 0; q < np; q++) { exhi[q] = -1; eyhi[q] = -1; ez[q] = -1; }

        _ctx c = { ni, nj, k, x0, h, iso, vlo, vhi,
                   exlo, exhi, eylo, eyhi, ez, m };

        for (int j = 0; j < nj-1 && !err; j++) {
            for (int i = 0; i < ni-1 && !err; i++) {
                // Bit ligado quando o valor fica ABAIXO do iso.  Esta e' a
                // convencao da tabela; invertida, ela devolve a superficie
                // com a orientacao trocada (e o volume negativo, que a
                // correcao no fim deste arquivo apanharia).
                const double vv[8] = {
                    vlo[ j   *ni + i  ], vlo[ j   *ni + i+1],
                    vlo[(j+1)*ni + i+1], vlo[(j+1)*ni + i  ],
                    vhi[ j   *ni + i  ], vhi[ j   *ni + i+1],
                    vhi[(j+1)*ni + i+1], vhi[(j+1)*ni + i  ]
                };
                int ci = 0;
                for (int q = 0; q < 8; q++) if (vv[q] < iso) ci |= (1 << q);
                if (mc_tri[ci][0] < 0) continue;

                for (int q = 0; mc_tri[ci][q] >= 0; q += 3) {
                    int a = _vert(&c, i, j, mc_tri[ci][q  ]);
                    int b = _vert(&c, i, j, mc_tri[ci][q+1]);
                    int d = _vert(&c, i, j, mc_tri[ci][q+2]);
                    if (a < 0 || b < 0 || d < 0) { err = 1; break; }
                    if (a == b || b == d || a == d) continue;  // degenerado
                    if (_cresce_t(m)) { err = 1; break; }
                    m->t[3*m->nt+0] = a; m->t[3*m->nt+1] = b;
                    m->t[3*m->nt+2] = d; m->nt++;
                }
            }
        }
        // troca as fatias
        double *tv = vlo; vlo = vhi; vhi = tv;
        int *tx = exlo; exlo = exhi; exhi = tx;
        int *ty = eylo; eylo = eyhi; eyhi = ty;
    }
    free(vlo);free(vhi);free(exlo);free(exhi);free(eylo);free(eyhi);free(ez);
    if (err) return 1;

    // ORIENTACAO.  Em vez de confiar na convencao da tabela, mede-se: o
    // volume encerrado por uma superficie fechada com normal para fora e'
    // positivo.  Se saiu negativo, a superficie esta' do lado errado e
    // inverte-se o enrolamento de todos os triangulos.  Isto so' faz sentido
    // porque a tabela e' globalmente consistente -- o que mc_arestas_orfas
    // confirma.
    if (mc_volume(m) < 0.0)
        for (int q = 0; q < m->nt; q++) {
            int tmp = m->t[3*q+1]; m->t[3*q+1] = m->t[3*q+2]; m->t[3*q+2] = tmp;
        }

    // Normal por vertice: media das normais dos triangulos pesada pela area
    // (o produto vetorial nao normalizado ja' tras o peso).  E' a normal do
    // que foi de fato emitido, nao a do gradiente do campo -- e' o que o
    // renderizador quer para sombrear sem facetas.
    for (int q = 0; q < 3*m->nv; q++) m->vn[q] = 0.0;
    for (int q = 0; q < m->nt; q++) {
        const double *A = &m->v[3*m->t[3*q+0]];
        const double *B = &m->v[3*m->t[3*q+1]];
        const double *C = &m->v[3*m->t[3*q+2]];
        double u[3], w[3], n[3];
        for (int d = 0; d < 3; d++) { u[d] = B[d]-A[d]; w[d] = C[d]-A[d]; }
        n[0] = u[1]*w[2]-u[2]*w[1];
        n[1] = u[2]*w[0]-u[0]*w[2];
        n[2] = u[0]*w[1]-u[1]*w[0];
        for (int r = 0; r < 3; r++)
            for (int d = 0; d < 3; d++) m->vn[3*m->t[3*q+r]+d] += n[d];
    }
    for (int q = 0; q < m->nv; q++) {
        double *n = &m->vn[3*q];
        double s = sqrt(n[0]*n[0]+n[1]*n[1]+n[2]*n[2]);
        if (s > 0.0) { n[0]/=s; n[1]/=s; n[2]/=s; }
    }
    return 0;
}

