// ------------------------------------------------------------------------
// Conferencia da tabela contra a geometria do cubo.
//
// A tabela acima e' dado copiado; um digito trocado nela produz um buraco
// na superficie que passa facil por "detalhe de renderizacao".  Esta funcao
// nao compara com uma segunda tabela escrita a mao -- ela DERIVA, do proprio
// caso c, quais arestas tem de estar cortadas (extremos com sinais opostos)
// e exige que o conjunto usado pela tabela seja exatamente esse.
// ------------------------------------------------------------------------
int mc_verifica_tabela(void) {
    int ruins = 0;
    for (int c = 0; c < 256; c++) {
        // conjunto exigido pela geometria
        int exigido = 0;
        for (int e = 0; e < 12; e++) {
            int a = (c >> mc_ar[e][0]) & 1;
            int b = (c >> mc_ar[e][1]) & 1;
            if (a != b) exigido |= (1 << e);
        }
        // conjunto que a tabela usa, e sanidade do formato
        int usado = 0, n = 0, mau = 0;
        for (n = 0; n < 16 && mc_tri[c][n] >= 0; n++) {
            if (mc_tri[c][n] > 11) { mau = 1; break; }
            usado |= (1 << mc_tri[c][n]);
        }
        if (n % 3 != 0) mau = 1;                  // triangulos incompletos
        for (int k = n; k < 16; k++)              // nada depois do -1
            if (mc_tri[c][k] != -1) mau = 1;
        if (usado != exigido) mau = 1;
        if (mau) ruins++;
    }
    return ruins;
}

